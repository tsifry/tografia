uint32_t* _keySchedule(uint8_t* chave, const uint8_t* sbox_encrypt){
    
    //Array de setup pro Round constant Rcon
    uint32_t rconArray[10] = {0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x3 };
    int rconCount = 0;

    //Cada key nesse array é 4elementos de 4bytes = 16bytes.
    uint32_t* keysArray = malloc(44 * sizeof(uint32_t));
    uint32_t* chave4bytesBlock = (uint32_t *)chave;

    //K0 é a nossa chave original.
    for(int i = 0; i < 4; i++){
        keysArray[i] = chave4bytesBlock[i];
    }

    for(int i = 4; i <= 43; i++){

        if(i % 4 != 0){
            keysArray[i] = keysArray[i - 1] ^ keysArray[i - 4];
        }
        else
        {   
            uint32_t temp = keysArray[i - 1];

            //RotWorld -> Rotaciona pra esquerda uma vez
            temp = (temp << 8) | (temp >> 24);
            uint8_t* bytes = (uint8_t*)&temp;
            
            //Aplica sBox
            for(int y = 0; y < 4; y++){
                bytes[y] = sbox_encrypt[bytes[y]];
            }
            
            //XOR com o Round constant
            bytes[0] ^= rconArray[rconCount];
            keysArray[i] = temp ^ keysArray[i - 4]; //XOR final

            rconCount++;
        }
    }

}

uint8_t** _createMatriz(uint8_t* buffer){

    uint8_t** m = malloc(4 * sizeof(uint8_t*));
    const int grid_size = 4;

    for(int i = 0; i < grid_size; i++){
        m[i] = malloc(grid_size * sizeof(uint8_t));
    }

    //Cria matriz
    for(int y = 0; y < grid_size; y++){
        for(int z = 0; z < grid_size; z++){
            m[z][y] = *buffer;
            buffer++;
        }
    }

    return m;
}

void _encryptSbox(uint8_t** matriz, const uint8_t* sbox_encrypt){

    int grid_size = 4;

    //S-Box nos bytes da matriz
    for(int y = 0; y < grid_size; y++){

        for(int z = 0; z < grid_size; z++){
            matriz[z][y] = sbox_encrypt[matriz[z][y]];
        }
    }
}

void _encryptShiftRows(uint8_t** matriz){

    const int shift_matrice[4][4] = {
        {0, 1, 2, 3},
        {1, 2, 3, 0},
        {2, 3, 0, 1},
        {3, 0, 1, 2}
    };

    const int grid_size = 4;

    //ShiftRows
    uint8_t* tempRow = malloc(4 * sizeof(uint8_t));
    for(int y = 0; y < grid_size; y++){

        for(int x = 0; x < grid_size; x++){
            tempRow[x] = matriz[y][x];
        }
                
        for(int z = 0; z < grid_size; z++){
            matriz[y][z] = tempRow[shift_matrice[y][z]];
        }
    }
    free(tempRow);
}

void _mixColl(uint8_t** matriz){

    const int constMatriz[4][4] = {
        {2, 3, 1, 1},
        {1, 2, 3, 1},
        {1, 1, 2, 3},
        {3, 1, 1, 2}
    };

    const int grid_size = 4;

    uint8_t* tempColl = malloc(4 * sizeof(uint8_t));

    //Pra cada coluna da matriz
    for(int col = 0; col < grid_size; col++){
        uint8_t res = 0;

        //Guarda a coluna em um array temporario
        for(int x = 0; x < grid_size; x++){
            tempColl[x] = matriz[x][col];
        }

        //Calcula multiplicação de matriz dado uma coluna k
        for(int j = 0; j < grid_size; j++){

            //Faz o dot product entre rx * k
            for(int y = 0; y < grid_size; y++){

                uint8_t mul = xmul(constMatriz[j][y], tempColl[y]);
                res ^= mul;
            }
            
            matriz[j][col] = res;
            res = 0;
        }
    }

    free(tempColl);
}


uint8_t xmul(uint8_t a, uint8_t b){
    uint8_t result = 0;

    while(b != 0){

        if(b & 1){
            result ^= a;
        }
        
        //Reduz se necessário
        if(a & 0x80)
        {
           a = (a << 1) ^ 0x1B; //Reduz pelo Rjindael x^4 + x^3 + x + 1
        }
        else
        {
            //Shift esquerdo = Ax * x
            a <<= 1;
        }

        //Shift direito
        b >>= 1;
    }

    return result;

}

